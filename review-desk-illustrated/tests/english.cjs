const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const {pathToFileURL} = require('node:url');
const path = require('node:path');
const fs = require('node:fs/promises');
const os = require('node:os');

(async () => {
  const browser = await chromium.launch({executablePath:process.env.EDGE_PATH || undefined});
  const dir = await fs.mkdtemp(path.join(os.tmpdir(),'review-english-'));
  try {
    const context = await browser.newContext({acceptDownloads:true,viewport:{width:1280,height:1000}});
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto(pathToFileURL(path.resolve(__dirname,'../index.html')).href);
    await page.locator('#preview img').waitFor();
    assert.match(await page.locator('h1').innerText(),/Palette tool/);
    assert(await page.locator('#preview img').evaluate(i=>i.naturalWidth>0));
    if (process.env.REVIEW_SCREENSHOT) await page.screenshot({path:process.env.REVIEW_SCREENSHOT,fullPage:true});
    await page.getByRole('button',{name:/Show confirmation after copying/}).click();
    await page.waitForFunction(()=>Math.abs(document.querySelector('#preview video')?.currentTime-1.5)<0.05);
    await page.getByRole('button',{name:/Document the keyboard controls/}).click();
    assert.match(await page.locator('.paragraph.selected').innerText(),/Press Tab/);
    await page.getByRole('button',{name:'Project tools'}).click();
    await page.getByRole('button',{name:'Requirements & AI checklist'}).click();
    await page.locator('#requirement').fill('A copy button shows a confirmation.');
    await page.locator('#ai-list').fill(JSON.stringify([{title:'Copy confirmation',detail:'Show the copied value.'}]));
    await page.getByRole('button',{name:'Save',exact:true}).click();
    await page.locator('#dialog').waitFor({state:'hidden'});
    assert.equal(await page.locator('[data-item]').count(),4);
    await page.getByRole('button',{name:/Show the palette/}).click();
    await page.getByRole('button',{name:'Needs changes',exact:true}).click();
    await page.locator('#reason').fill('Adjust the color.');
    await page.getByRole('button',{name:'Save',exact:true}).click();
    await page.locator('#dialog').waitFor({state:'hidden'});
    await page.getByRole('button',{name:'Project tools'}).click();
    await page.getByRole('button',{name:'Generate revision instructions'}).click();
    assert.match(await page.locator('#instruction-text').inputValue(),/Adjust the color/);
    await page.locator('#cancel').click();
    await page.locator('#dialog').waitFor({state:'hidden'});
    await page.getByRole('button',{name:'Project tools'}).click();
    const download = page.waitForEvent('download');
    await page.getByRole('button',{name:'Export project backup'}).click();
    const backup = path.join(dir,'backup.json');
    await (await download).saveAs(backup);
    await page.getByRole('button',{name:'Project tools'}).click();
    await page.getByRole('button',{name:'Import project backup'}).click();
    await page.locator('#backup-file').setInputFiles(backup);
    await page.getByRole('button',{name:'Save',exact:true}).click();
    await page.locator('#dialog').waitFor({state:'hidden'});
    assert.match(await page.locator('h1').innerText(),/imported/);
    await page.locator('#preview img').waitFor();
    assert(await page.locator('#preview img').evaluate(i=>i.naturalWidth>0));
    await page.getByRole('button',{name:'Export report'}).click();
    const report = page.waitForEvent('download');
    await page.getByRole('button',{name:'Export',exact:true}).click();
    const reportPath = path.join(dir,'report.html');
    await (await report).saveAs(reportPath);
    const reportPage = await context.newPage();
    await reportPage.goto(pathToFileURL(reportPath).href);
    assert.match(await reportPage.locator('body').innerText(),/Review note/);
    assert.deepEqual(errors,[]);
    console.log('PASS English demo, AI checklist, review, revisions, backup, restore and HTML report');
  } finally {
    await browser.close();
    await fs.rm(dir,{recursive:true,force:true});
  }
})().catch(error=>{console.error(error);process.exitCode=1;});
